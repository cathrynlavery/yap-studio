#!/usr/bin/env python3
"""Regenerate style-data.js for the style page prototype.

The page reads a copy of the style schema and presets because browsers block
file:// requests for JSON. This script rebuilds that copy from the source files
so the JSON stays the source of truth.
The caption preview scripts and CSS also come from the engine template.

    python3 docs/design/style-page/sync_data.py
    python3 docs/design/style-page/sync_data.py --check

The engine's style folder is the default source. Only the shipped presets listed
in SHIPPED come from STYLE_DIR/presets. Proposed presets
come from proposed-presets/ next to this script and are marked so the page can
tell them apart. Creator files (STYLE_DIR/creators) are never read. The page
only needs the schema's rules, so the copy drops its $id and description.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "style-data.js"
PORT_JS = HERE / "caption-ports.js"
PORT_CSS = HERE / "caption-ports.css"
PROPOSED = HERE / "proposed-presets"
# Shipped presets creators may see. Anything not listed here stays out.
SHIPPED = [
    "editorial_serif", "clean_minimal", "warm_editorial", "cobalt", "mono",
    "headline", "electric", "candy", "marker", "one_word", "hf_bold", "hf_editorial", "hf_neutral",
]


def _read(path: Path) -> dict:
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise SystemExit(f"{path}: expected a JSON object")
    return data


def _ordered(folder: Path, first: list[str]) -> list[Path]:
    files = {p.stem: p for p in sorted(folder.glob("*.json")) if p.name != "order.json"}
    missing = [name for name in first if name not in files]
    if missing:
        raise SystemExit(f"{folder}: missing presets {', '.join(missing)}")
    rest = [name for name in files if name not in first]
    return [files[name] for name in first + rest]


def build(style_dir: Path) -> str:
    schema = _read(style_dir / "schema-v1.json")
    for key in ("$id", "description"):
        schema.pop(key, None)
    presets = []
    for name in SHIPPED:
        path = style_dir / "presets" / f"{name}.json"
        if not path.is_file():
            raise SystemExit(f"{path}: missing shipped preset")
        presets.append({"id": name, "proposed": False, "style": _read(path)})
    if PROPOSED.is_dir():
        order = json.loads((PROPOSED / "order.json").read_text(encoding="utf-8"))
        for path in _ordered(PROPOSED, order):
            presets.append({"id": path.stem, "proposed": True, "style": _read(path)})
    payload = json.dumps({"schema": schema, "presets": presets}, indent=2, ensure_ascii=False)
    return (
        "// Generated by sync_data.py from schema-v1.json and the preset files.\n"
        "// Do not edit by hand; edit the JSON and run the script again.\n"
        f"window.YAP_STYLE_DATA = {payload};\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "style_dir",
        type=Path,
        nargs="?",
        default=HERE.parents[2] / "src" / "yap_studio" / "style",
        help="style folder (defaults to the engine's style folder)",
    )
    parser.add_argument("--check", action="store_true", help="fail if generated page data is stale")
    args = parser.parse_args(argv)
    text = build(args.style_dir.expanduser())
    source = (HERE.parents[2] / "src/yap_studio/templates/captions/template.html").read_text()
    css = source.split("/* Registry ports keep", 1)[1].split("</style>", 1)[0]
    helpers = source.split("// BEGIN_CAPTION_PORTS:", 1)[1].split("\n", 1)[1]
    helpers = helpers.split("  // END_CAPTION_PORTS", 1)[0]
    case_helpers = re.search(r"  // BEGIN_CAPTION_CASE\n(.*?)  // END_CAPTION_CASE\n",
                             helpers, re.DOTALL)
    assert case_helpers is not None
    helpers = helpers.replace(case_helpers[0], "")
    ports = re.search(r"const portedLook = (\[.*?\])\.includes", source, re.DOTALL)
    assert ports is not None
    solid = re.search(r"const solidCoreLook = (\[.*?\])\.includes", source, re.DOTALL)
    assert solid is not None
    js = (
        "// Generated by sync_data.py from the engine caption template.\n"
        "// Derived from HyperFrames caption styles; see templates/PROVENANCE.json.\n"
        "// Copyright 2026 HeyGen, Inc. Apache License 2.0 (LICENSES/Apache-2.0.txt).\n"
        "// Modified for Yap Studio, 2026: shared word timing, "
        "style tokens and seekable previews.\n"
        "(() => {\n  'use strict';\n"
        f"  const styles = {ports[1]};\n"
        f"  const solidCoreStyles = {solid[1]};\n"
        + case_helpers[1]
        + "  function build(v, phrase, spans, words, duration) {\n"
        "    const offset = (time) => Math.max(0, Math.min(1, time / duration));\n"
        "    const ease = 'cubic-bezier(.2,.7,.2,1)';\n"
        "    const shadow = `${v.shadow_x_px}px ${v.shadow_y_px}px ${v.shadow_blur_px}px ` +\n"
        "      `rgb(0 0 0 / ${v.shadow_opacity})`;\n"
        + helpers
        + "    spans.forEach((span, index) => "
        "decorateWord(span, phrase.words[index], index, phrase));\n"
        "    if (v.highlight_style === 'camera_follow') animateCamera(words, phrase);\n"
        "    const animations = words.getAnimations({subtree: true});\n"
        "    animations.forEach((animation) => { "
        "animation.pause(); animation.currentTime = 0; });\n"
        "    return {\n"
        "      seek(time) { animations.forEach((animation) => { "
        "animation.currentTime = time * 1000; }); },\n"
        "      cancel() { animations.forEach((animation) => animation.cancel()); },\n"
        "    };\n"
        "  }\n"
        "  const api = {supports: (style) => styles.includes(style), build, "
        "solidCore: (style) => solidCoreStyles.includes(style), "
        "wordCase: captionWordCase, applyWordCase};\n"
        "  if (typeof module !== 'undefined' && module.exports) module.exports = api;\n"
        "  else window.YapCaptionPorts = api;\n"
        "})();\n"
    )
    generated = {OUT: text, PORT_JS: js,
                 PORT_CSS: "/* Generated by sync_data.py from the engine caption template. */\n"
                 "/* Copyright 2026 HeyGen, Inc. Apache License 2.0 (LICENSES/Apache-2.0.txt).\n"
                 "   Modified for Yap Studio, 2026: shared caption preview styles. */\n"
                 "/* Registry ports keep" + css}
    if args.check:
        stale = [file.name for file, expected in generated.items()
                 if not file.exists() or file.read_text(encoding="utf-8") != expected]
        if stale:
            print(f"{', '.join(stale)} is stale; run sync_data.py again", file=sys.stderr)
            return 1
        print("style-data.js matches the source files")
        return 0
    for file, text in generated.items():
        file.write_text(text, encoding="utf-8")
        print(f"wrote {file.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
