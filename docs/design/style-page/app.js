  function rangeField({ label, path, min, max, step, format, valueText, hint, ends }) {
    const r = rule(path);
    const id = `f-${++uid}`;
    const value = el('span', { class: 'field-value', 'aria-hidden': 'true' });
    const hintNode = hint ? el('p', { class: 'field-hint', id: `${id}-hint` }, hint) : null;
    const input = el('input', { type: 'range', class: 'range', id, min, max, step, 'aria-describedby': hintNode ? `${id}-hint` : null });
    input.addEventListener('input', () => {
      const v = r.type === 'integer' ? Math.round(+input.value) : Math.round(+input.value * 100) / 100;
      update(path, v);
    });
    const node = el('div', { class: 'field' },
      el('div', { class: 'field-row' }, el('label', { class: 'field-label', for: id }, label), value),
      el('div', { class: 'range-wrap' },
        el('span', { class: 'range-end', 'aria-hidden': 'true' }, ends[0]), input,
        el('span', { class: ends[1] === 'A' ? 'range-end range-end--big' : 'range-end', 'aria-hidden': 'true' }, ends[1])),
      hintNode);
    syncers.push((s) => {
      const v = get(s, path);
      const top = Math.max(max, v);
      input.max = top;
      input.value = v;
      input.style.setProperty('--fill', `${((v - min) / (top - min)) * 100}%`);
      input.setAttribute('aria-valuetext', valueText(v));
      value.textContent = format(v);
    });
    return node;
  }

