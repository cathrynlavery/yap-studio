    async function pullColors() {
      const raw = siteInput.value.trim();
      if (!raw) { siteStatus.textContent = 'Enter your website address first.'; siteInput.focus(); return; }
      siteBtn.disabled = true;
      siteBtn.textContent = 'Getting colors…';
      siteStatus.textContent = `Reading ${raw}…`;
      found.hidden = true;
      const ctl = new AbortController();
      // serve.py stops looking after 25 seconds, so this only fires if it hangs.
      const timer = setTimeout(() => ctl.abort(), 40000);
      try {
        const res = await fetch(`/api/site-colors?url=${encodeURIComponent(raw)}`, { signal: ctl.signal });
        const body = await res.json();
        if (!res.ok) throw new Error(body.error || 'That site could not be read.');
        const s = body.suggestion;
        setColors({ caption: s.caption, accent: s.accent || state.custom.accent, paper: s.paper, ink: s.ink });
        const kept = s.accent ? '' : ` ${body.site} is mostly black and white, so we kept your highlight color.`;
        siteStatus.textContent = `Filled in from ${body.site}.${kept}`;
        showFound(body.colors);
      } catch (e) {
        const offline = location.protocol === 'file:' || e instanceof TypeError || e instanceof SyntaxError;
        if (offline) console.info('Website colors need serve.py: run python3 serve.py and open the address it prints');
        siteStatus.textContent = e.name === 'AbortError' ? 'That site took too long. Try again, or type hex codes above.'
          : offline ? 'Pulling colors from a website isn’t available right now. Type hex codes above instead.'
            : `${e.message} You can type hex codes above instead.`;
      } finally {
        clearTimeout(timer);
        siteBtn.disabled = false;
        siteBtn.textContent = 'Get colors';
      }
    }
    siteBtn.addEventListener('click', pullColors);
    siteInput.addEventListener('keydown', (e) => { if (e.key === 'Enter') { e.preventDefault(); pullColors(); } });

